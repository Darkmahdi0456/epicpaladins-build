#!/usr/bin/env python3
"""Static audit of Epic Paladins armor piece -> equipment slot wiring."""
from pathlib import Path
import re, json
ROOT = Path(__file__).resolve().parent
SRC = ROOT / 'src/main/java/net/veroxuniverse/epicpaladins/fabric/ArmorItemsRegistry.java'
ITEM = ROOT / 'src/main/java/net/veroxuniverse/epicpaladins/fabric/item/GeoArmorItem.java'
REG = SRC.read_text(encoding='utf-8')
GEO = ITEM.read_text(encoding='utf-8')
sets = re.findall(r'addSet\("([a-z0-9_]+)"', REG)
expected = {'helmet':'EquipmentType.HELMET','chestplate':'EquipmentType.CHESTPLATE','leggings':'EquipmentType.LEGGINGS','boots':'EquipmentType.BOOTS'}
checks=[]
for suffix, enum in expected.items():
    checks.append((f'{suffix} registered with correct EquipmentType', f'registerPiece(id + \"_{suffix}\", material, {enum})' in REG))
checks.append(('all nine armor sets registered', len(sets)==9))
checks.append(('36 armor pieces are generated by four registrations per set', all(x in REG for x in expected.values()) and len(sets)*4==36))
checks.append(('each item receives its armor set id', 'id.substring(0, id.lastIndexOf(\'_\'))' in REG))
checks.append(('GeoArmorItem extends ArmorItem', 'extends ArmorItem' in GEO))
checks.append(('renderer receives entity, stack, slot and original model', all(x in GEO for x in ['livingEntity','itemStack','equipmentSlot','original'])))
checks.append(('renderer is prepared before return', 'prepForRender(livingEntity, itemStack, equipmentSlot, original)' in GEO))
checks.append(('renderer class is client-only', '@Environment(EnvType.CLIENT)' in (ROOT/'src/main/java/net/veroxuniverse/epicpaladins/fabric/client/armor/ArmorGeoRenderer.java').read_text(encoding='utf-8')))
print('Armor slot audit')
for name, ok in checks: print(('PASS' if ok else 'FAIL')+' '+name)
print(f'SUMMARY {sum(ok for _,ok in checks)}/{len(checks)}')
if not all(ok for _,ok in checks): raise SystemExit(1)
